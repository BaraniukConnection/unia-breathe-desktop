#!/usr/bin/env bash
# Hooks Unia Breathe Desktop into the system with symlinks (safe to run again).
set -euo pipefail
REPO="$(cd "$(dirname "$0")" && pwd)"

mkdir -p ~/.config/quickshell ~/.config/unia-breathe
touch ~/.config/unia-breathe/hyprland.conf                # generated by Settings; must exist for source
ln -sfn "$REPO/quickshell" ~/.config/quickshell/unia      # run with: qs -c unia
mkdir -p ~/.local/bin
for f in "$REPO"/bin/* "$REPO"/quickshell/components/*/bin/*; do ln -sfn "$f" ~/.local/bin/"$(basename "$f")"; done

# lock screen (hyprlock reads ~/.config/hypr/hyprlock.conf)
ln -sfn "$REPO/hypr/hyprlock.conf" ~/.config/hypr/hyprlock.conf

# GTK: the adw-gtk3-dark theme + the Unia Breathe Desktop palette
# if nwg-look made gtk.css a symlink to a theme, import that theme first and the Unia palette on top
for v in 3 4; do
    f=~/.config/gtk-$v.0/gtk.css
    mkdir -p "$(dirname "$f")"
    base=""
    if [ -L "$f" ]; then base=$(readlink -f "$f"); rm "$f"; fi
    {
        echo "/* Unia Breathe Desktop */"
        [ -n "$base" ] && echo "@import url(\"file://$base\");"
        echo "@import url(\"file://$REPO/gtk/gtk$v.css\");"
    } > "$f"
done
gsettings set org.gnome.desktop.interface gtk-theme adw-gtk3-dark
gsettings set org.gnome.desktop.interface color-scheme prefer-dark
for f in ~/.config/gtk-3.0/settings.ini ~/.config/gtk-4.0/settings.ini; do
    [ -f "$f" ] || printf '[Settings]\n' > "$f"
    sed -i '/^gtk-theme-name=/d; /^gtk-application-prefer-dark-theme=/d' "$f"
    sed -i 's/^\[Settings\]$/[Settings]\ngtk-theme-name=adw-gtk3-dark\ngtk-application-prefer-dark-theme=true/' "$f"
done

# kitty: palette
grep -qF "unia-theme.conf" ~/.config/kitty/kitty.conf 2>/dev/null || printf '\n# Unia Breathe Desktop\ninclude %s/kitty/unia-theme.conf\n' "$REPO" >> ~/.config/kitty/kitty.conf

HYPR=~/.config/hypr/hyprland.conf
LINE="source = $REPO/hypr/unia.conf"
grep -qxF "$LINE" "$HYPR" || printf '\n# Unia Breathe Desktop\n%s\n' "$LINE" >> "$HYPR"

echo "Unia Breathe Desktop is hooked up: $REPO"
